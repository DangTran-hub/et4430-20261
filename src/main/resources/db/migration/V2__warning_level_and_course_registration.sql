-- Các quyết định thiết kế được ghi trong docs/data/database-setup.md.

-- Mức cảnh báo học tập của sinh viên (UC1 bước 7 cần hiển thị).
-- 0 = bình thường, 1..3 = cảnh báo mức 1..3. Giới hạn tín chỉ theo mức nằm trong
-- WarningPolicy (Java): 0 -> 12..24 TC, 1 -> tối đa 14, 2 -> tối đa 10, 3 -> không được đăng ký.
ALTER TABLE student_profile
    ADD COLUMN academic_warning_level INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_student_warning_level CHECK (academic_warning_level BETWEEN 0 AND 3);

-- UC1 4a: mỗi học kỳ chỉ có một đợt đăng ký chưa bị hủy.
CREATE UNIQUE INDEX uq_registration_campaign_term_active
    ON registration_campaign (term_id)
    WHERE status <> 'CANCELLED';

-- Công bố lặp lại không sinh thêm thông báo.
ALTER TABLE notification
    ADD CONSTRAINT uq_notification_campaign UNIQUE (campaign_id);

-- Sinh viên đăng ký học phần trong một đợt.
CREATE TABLE course_registration (
    registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES student_profile(student_id),
    campaign_course_id BIGINT NOT NULL REFERENCES campaign_course(campaign_course_id),
    status TEXT NOT NULL,
    registered_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_course_registration UNIQUE (student_id, campaign_course_id)
);
