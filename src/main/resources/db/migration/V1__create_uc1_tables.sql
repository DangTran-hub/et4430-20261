-- UC1 foundation. Unresolved workflow decisions are documented in docs/data/database-setup.md.
CREATE TABLE user_account (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    email TEXT,
    role TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE student_profile (
    student_id BIGINT PRIMARY KEY REFERENCES user_account(user_id),
    student_code TEXT NOT NULL UNIQUE,
    program_code TEXT,
    cohort_year INTEGER,
    class_code TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE academic_term (
    term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year TEXT NOT NULL,
    term_code TEXT NOT NULL,
    term_start_date DATE NOT NULL,
    term_end_date DATE NOT NULL,
    status TEXT NOT NULL,
    CONSTRAINT uq_academic_term UNIQUE (academic_year, term_code),
    CONSTRAINT ck_term_dates CHECK (term_end_date > term_start_date)
);

CREATE TABLE course (
    course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code TEXT NOT NULL UNIQUE,
    course_name TEXT NOT NULL,
    credits NUMERIC(6,2) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE course_term_rule (
    rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES course(course_id),
    term_code TEXT NOT NULL,
    program_code TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE registration_campaign (
    campaign_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id BIGINT NOT NULL REFERENCES academic_term(term_id),
    registration_open_at TIMESTAMP WITH TIME ZONE,
    registration_close_at TIMESTAMP WITH TIME ZONE,
    status TEXT NOT NULL,
    copied_from_campaign_id BIGINT REFERENCES registration_campaign(campaign_id),
    created_by BIGINT NOT NULL REFERENCES user_account(user_id),
    approved_by BIGINT REFERENCES user_account(user_id),
    approved_at TIMESTAMP WITH TIME ZONE,
    published_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_registration_dates CHECK (registration_close_at > registration_open_at)
);

CREATE TABLE campaign_course (
    campaign_course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES registration_campaign(campaign_id),
    course_id BIGINT NOT NULL REFERENCES course(course_id),
    copied_from_campaign_course_id BIGINT REFERENCES campaign_course(campaign_course_id),
    offering_status TEXT NOT NULL,
    CONSTRAINT uq_campaign_course UNIQUE (campaign_id, course_id)
);

CREATE TABLE notification (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES registration_campaign(campaign_id),
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by BIGINT NOT NULL REFERENCES user_account(user_id)
);
